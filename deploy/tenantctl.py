#!/usr/bin/env python3
"""Operator-only provisioning. Each organization gets its own application stack."""
import argparse
import contextlib
import fcntl
import json
import os
from pathlib import Path
import re
import secrets
import socket
import subprocess
from urllib.parse import urlsplit

REPO = Path(__file__).resolve().parents[1]
DEFAULT_ROOT = Path("/var/lib/convenecore/tenants")
SLUG = re.compile(r"[a-z][a-z0-9-]{1,39}")
HOST = re.compile(r"(?=.{4,253}$)(?:[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z][a-z0-9-]{1,62}")
EMAIL = re.compile(r"[^\s'\x00-\x1f]+@[^\s'\x00-\x1f]+")


def private_write(path, data):
    tmp = path.with_name("." + path.name + "." + secrets.token_hex(8))
    try:
        fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
        with os.fdopen(fd, "w") as handle:
            handle.write(data)
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(tmp, path)
    finally:
        tmp.unlink(missing_ok=True)


@contextlib.contextmanager
def registry(root):
    root.mkdir(mode=0o700, parents=True, exist_ok=True)
    if root.is_symlink() or root.stat().st_mode & 0o077:
        raise RuntimeError("Registry must be an operator-owned private directory (0700)")
    with (root / ".lock").open("a") as handle:
        fcntl.flock(handle, fcntl.LOCK_EX)
        path = root / "registry.json"
        rows = json.loads(path.read_text()) if path.exists() else {}
        yield rows
        private_write(path, json.dumps(rows, indent=2) + "\n")


def validate(slug, host, email, port):
    if not SLUG.fullmatch(slug):
        raise ValueError("Use a 2–40 character lowercase organization slug")
    if not HOST.fullmatch(host) or host.endswith("-"):
        raise ValueError("Use an exact public DNS hostname")
    if not EMAIL.fullmatch(email) or len(email)>254:
        raise ValueError("Invalid administrator email")
    if not 1024 <= port <= 65535:
        raise ValueError("Port must be between 1024 and 65535")


def compose_env(row):
    return {
        "TENANT_ID": row["slug"],
        "FRONTEND_PORT": str(row["port"]),
        "PUBLIC_APP_URL": "https://" + row["host"],
        "NEXT_PUBLIC_API_URL": "https://" + row["host"],
        "SCHOOL_NAME": row["slug"].replace("-", " ").title(),
        "DB_USER": "cc_" + row["slug"].replace("-", "_"),
        "DB_PASSWORD": secrets.token_hex(32),
        "SECRET_KEY": secrets.token_urlsafe(64),
        "ADMIN_EMAIL": row["admin_email"],
        "ADMIN_PASSWORD": "Cc!" + secrets.token_urlsafe(25),
        "SMTP_HOST": "",
        "SMTP_USERNAME": "",
        "SMTP_PASSWORD": "",
        "SMTP_FROM_EMAIL": "notifications@" + row["host"],
        "SMTP_VERIFY_TLS": "true",
        "GEMINI_API_KEY": "",
    }


def dotenv(values):
    if any("\n" in v or "\r" in v or "'" in v for v in values.values()):
        raise ValueError("Invalid environment value")
    return "".join(f"{k}='{v}'\n" for k,v in values.items())


def provision(root, rows, slug, host, email, port):
    validate(slug, host, email, port)
    if slug in rows or any(r["host"] == host or r["port"] == port for r in rows.values()):
        raise ValueError("Organization slug, hostname and frontend port must each be unique")
    with socket.socket() as sock:
        sock.bind(("127.0.0.1", port))
    directory = root / slug
    directory.mkdir(mode=0o700, exist_ok=False)
    row = {"slug":slug,"host":host,"port":port,"admin_email":email,"enabled":False}
    private_write(directory / "tenant.env", dotenv(compose_env(row)))
    rows[slug] = row
    return row


def compose_command(root, row, *args):
    return ["docker","compose","--project-name","cc-"+row["slug"],
        "--env-file",str(root / row["slug"] / "tenant.env"),
        "-f",str(REPO / "docker-compose.yml"),"-f",str(REPO / "deploy/compose.tenant.yml"),*args]


def run_compose(root, row, *args):
    # Shell environment must not override a tenant's credentials or volume names.
    env={k:os.environ[k] for k in ("PATH","HOME","LANG","LC_ALL","DOCKER_HOST","DOCKER_CONTEXT","DOCKER_CONFIG","XDG_RUNTIME_DIR") if k in os.environ}
    subprocess.run(compose_command(root,row,*args),cwd=REPO,env=env,check=True)


def nginx_config(rows):
    # Install into a trusted TLS reverse proxy after certificates are provisioned.
    parts=["# Generated by tenantctl. Never route unknown hosts to a default tenant."]
    for row in sorted(rows.values(),key=lambda x:x["host"]):
        if not row["enabled"]:
            continue
        h,p=row["host"],row["port"]
        validate(row["slug"],h,row["admin_email"],p)
        parts.append(f"""server {{
    listen 80;
    server_name {h};
    return 308 https://{h}$request_uri;
}}
server {{
    listen 443 ssl;
    server_name {h};
    ssl_certificate /etc/letsencrypt/live/{h}/fullchain.pem;
    ssl_certificate_key /etc/letsencrypt/live/{h}/privkey.pem;
    if ($host != {h}) {{ return 421; }}
    client_max_body_size 250m;
    location / {{
        proxy_pass http://127.0.0.1:{p};
        proxy_http_version 1.1;
        proxy_set_header Host {h};
        proxy_set_header X-Forwarded-Host {h};
        proxy_set_header X-Forwarded-Proto https;
        proxy_set_header X-Forwarded-For $remote_addr;
        proxy_read_timeout 300s;
        proxy_send_timeout 300s;
    }}
}}""")
    return "\n\n".join(parts)+"\n"


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root",type=Path,default=DEFAULT_ROOT)
    sub=parser.add_subparsers(dest="action",required=True)
    create=sub.add_parser("provision")
    create.add_argument("slug")
    create.add_argument("--host",required=True)
    create.add_argument("--admin-email",required=True)
    create.add_argument("--port",type=int,required=True)
    for action in ("start","suspend","status"):
        sub.add_parser(action).add_argument("slug")
    sub.add_parser("list")
    sub.add_parser("render-nginx")
    args=parser.parse_args()
    root=args.root.resolve()
    with registry(root) as rows:
        if args.action=="provision":
            row=provision(root,rows,args.slug,args.host,args.admin_email,args.port)
            print(json.dumps(row))
            print("Initial credentials are in the private tenant.env; deliver securely to the organization administrator.")
        elif args.action=="list":
            print(json.dumps(list(rows.values()),indent=2))
        elif args.action=="render-nginx":
            print(nginx_config(rows),end="")
        else:
            row=rows.get(args.slug)
            if not row:
                parser.error("Unknown organization")
            if args.action=="start":
                run_compose(root,row,"up","-d","--build","--wait")
                row["enabled"]=True
            elif args.action=="suspend":
                run_compose(root,row,"stop")
                row["enabled"]=False
            else:
                run_compose(root,row,"ps")


if __name__=="__main__":
    main()
