const assert=require('node:assert/strict');
const {classifyAudio}=require('/tmp/audio-health.js');
const peer={id:'a',label:'Guest',state:'connected',ice:'connected',rx:1000,tx:1000,received:50,lost:0,remoteMuted:false,expectedRx:true,expectedTx:true,playback:'playing',age:20000};
const base={online:true,reconnecting:false,speaker:true,blocked:false,forced:false,localMuted:false,mic:'live',peers:[peer],expectedPeers:1,statsAvailable:true};
const codes=(changes={},p={})=>classifyAudio({...base,...changes,peers:[{...peer,...p}]}).map(x=>x.code);
assert.deepEqual(codes(),[]);
assert.deepEqual(codes({online:false}),['offline']);
assert(codes({mic:'missing'}).includes('microphone'));
assert(codes({forced:true,localMuted:true}).includes('moderated'));
assert(codes({speaker:false}).includes('speaker-off'));
assert(codes({blocked:true}).includes('playback-blocked'));
assert(codes({}, {state:'failed',ice:'failed'}).includes('link-a'));
assert(!codes({}, {state:'new',age:4000}).includes('link-a'));
assert(codes({}, {rxAge:12000}).includes('rx-a'));
assert(codes({}, {txAge:12000}).includes('tx-a'));
assert(!codes({}, {expectedRx:false,rxAge:20000}).includes('rx-a'));
assert(!codes({}, {expectedTx:false,txAge:20000}).includes('tx-a'));
assert(codes({}, {playback:'paused'}).includes('play-a'));
assert(codes({}, {badQualityAge:8000}).includes('quality-a'));
assert(codes({}, {sourceSilentAge:20000}).includes('quiet-a'));
assert(!codes({}, {rxAge:8000,txAge:8000,badQualityAge:4000}).length);
console.log('PASS: 15 audio health classifications, intentional mute, silence, and startup grace');
